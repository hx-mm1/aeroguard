def _seed(tower_id: str) -> int:
    return zlib.crc32(tower_id.encode())


def _wave(seed: int, t_min: float, period: float) -> float:
    return math.sin(2 * math.pi * (t_min / period) + (seed % 997) / 997 * 2 * math.pi)


def _diurnal(hour: float) -> float:
    return (1.0 + 0.45 * math.exp(-((hour - 8.5) ** 2) / 4.5)
            + 0.35 * math.exp(-((hour - 19.0) ** 2) / 8.0) - 0.15 * math.exp(-((hour - 4.0) ** 2) / 8.0))


def fleet_status(now: pd.Timestamp, s: Settings, modes: dict, haze_regions: set,
                 live: dict) -> pd.DataFrame:
    """One row per tower with its current (simulated) state."""
    t_min = now.timestamp() / 60
    hour = now.hour + now.minute / 60
    rows = []
    for tw in FLEET:
        seed = _seed(tw.tower_id)
        if tw.tower_id == "AG-001":
            rows.append({**_static(tw), **live})
            continue
        status, note = _FAULTS.get(tw.tower_id, (ONLINE, "All systems normal"))
        pm25 = tw.base_pm25 * _diurnal(hour) * (1 + 0.12 * _wave(seed, t_min, 47) + 0.06 * _wave(seed >> 3, t_min, 11))
        if tw.region in haze_regions:
            pm25 += 48 + 6 * _wave(seed, t_min, 7)
        pm25 = max(pm25, 2.0)
        pm10 = pm25 * (1.7 + 0.15 * _wave(seed >> 5, t_min, 61))
        mode = modes.get(tw.tower_id, "AUTO")
        band = _band(pm25, s)
        if mode == "BOOST":
            fan = s.boost_pct
        elif mode == "ECO":
            fan = min(band_target(band, s), s.eco_cap_pct)
        else:
            fan = band_target(band, s)
        fan = clamp(fan, s.hard_min_pct, s.hard_max_pct)
        eff = 93.5 - 5 * (fan / 100 - 0.3) + 0.6 * _wave(seed >> 7, t_min, 90)
        airflow = s.rated_airflow_m3h * fan / 100 * 0.96
        power = 38 + 1050 * (fan / 100) ** 3
        dp = 175 + (seed % 60) + (95 if tw.tower_id == "AG-019" else 0)
        if status == OFFLINE:
            rows.append({**_static(tw), "status": status, "note": note, "mode": mode, "pm25": None, "pm10": None,
                         "fan_pct": None, "efficiency": None, "airflow": None, "power_w": None, "dp_pa": None})
            continue
        rows.append({**_static(tw), "status": status, "note": note, "mode": mode, "pm25": round(pm25, 1),
                     "pm10": round(pm10, 0), "fan_pct": round(fan, 0), "efficiency": round(eff, 1),
                     "airflow": round(airflow, -1), "power_w": round(power, 0), "dp_pa": round(dp, 0)})
    df = pd.DataFrame(rows)
    hours_today = max((now - now.normalize()).total_seconds() / 3600, 0.01)
    # rough "today so far" totals from the current operating point (demo estimate)
    df["energy_today_kwh"] = df["power_w"] * hours_today / 1000
    df["clean_air_today_m3"] = df["airflow"] * df["efficiency"] / 100 * hours_today
    return df


def _static(tw: Tower) -> dict:
    return {"tower_id": tw.tower_id, "site": tw.site, "city": tw.city, "state": tw.state, "region": tw.region,
            "lat": tw.lat, "lon": tw.lon, "setting": tw.setting}


def _band(pm25: float, s: Settings) -> str:
    edges = (s.pm25_low, s.pm25_high, s.pm25_critical)
    return BANDS[sum(pm25 >= e for e in edges)]


def pm_level(pm25, s: Settings) -> str:
    if pm25 is None or pd.isna(pm25):
        return "No data"
    return {"CLEAN": "Low", "ELEVATED": "Elevated", "HIGH": "High", "SEVERE": "Severe"}[_band(pm25, s)]
